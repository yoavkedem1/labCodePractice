import {lessons,notebookExport} from './notebook-lessons.js';
const root=document.querySelector('[data-notebook-lab]');
if(root) {
 const q=s=>root.querySelector(s);
 const BASE_CONFIG='[paths]\ndata = "../data/raw/trials.csv"\noutput = "../results/baseline"\n\n[preprocessing]\nmin_rt_s = 0.2\nmax_rt_s = 2.0\n';
 const storageKey='research-code-notebook-v1';
 let saved={};
 try{saved=JSON.parse(localStorage.getItem(storageKey)||'{}');}catch{saved={};}
 let lesson,worker,ready=false,busy=false,sequence=0,execution=0,pending=new Map();
 const message=text=>{q('[data-kernel-status]').textContent=text;q('[data-kernel-status]').closest('.kernel-line').dataset.state=busy?'busy':ready?'ready':'idle';};
 const sources=()=>[...root.querySelectorAll('[data-cell-code]')].map(e=>e.value);
 const workspace=()=>({'helpers.py':q('[data-helper]').value,'config/analysis.toml':q('[data-config]').value});
 function persist(){
   if(!lesson)return;
   saved[lesson.id]={sources:sources(),helper:q('[data-helper]').value,config:q('[data-config]').value,prediction:q('[data-prediction]').value};
   try{localStorage.setItem(storageKey,JSON.stringify(saved));}catch{message('Browser storage is unavailable. Download your notebook to keep edits.');}
 }
 function invalidate(){delete q('[data-mission-result]').dataset.state;q('[data-mission-result]').textContent='Edits changed the saved procedure. Rerun and check it again.';for(const output of root.querySelectorAll('[data-cell-output]')){if(output.textContent)output.dataset.stale='true';}persist();}
 function controls(){
   q('[data-kernel-status]').closest('.kernel-line').dataset.state=busy?'busy':ready?'ready':'idle';
   for(const b of root.querySelectorAll('[data-run-cell],[data-run-all],[data-check-mission],[data-save-file],[data-scenario],[data-solution],[data-reset-lesson]'))b.disabled=busy;
   q('[data-start-python]').disabled=busy||ready;
   q('[data-stop-python]').disabled=!worker;
   for(const e of root.querySelectorAll('[data-cell-code],[data-helper],[data-config]'))e.readOnly=busy;
 }
 function terminate(reason='Kernel restarted. Run cells again; previous variables and virtual files were cleared.'){
   worker?.terminate();worker=null;ready=false;execution=0;
   for(const request of pending.values()){clearTimeout(request.timer);request.reject(new Error(reason));}pending.clear();
   q('[data-variables]').textContent='No live variables. Start Python and run a cell.';
   for(const c of root.querySelectorAll('[data-cell-count]'))c.textContent='In [ ]';
   for(const o of root.querySelectorAll('[data-cell-output]'))if(o.textContent)o.dataset.stale='true';
   message(reason);controls();
 }
 function request(action,values={},timeout=15000){
   const id=++sequence;
   return new Promise((resolve,reject)=>{
     const timer=setTimeout(()=>{terminate('Execution timed out. The worker was stopped; restart and rerun your cells.');},timeout);
     pending.set(id,{resolve,reject,timer});
     worker.postMessage({id,action,...values});
   });
 }
 async function start(){
   if(ready)return;
   worker?.terminate();
   worker=new Worker(new URL('./python-worker.js',import.meta.url),{type:'module'});
   worker.onmessage=({data})=>{
     if(data.type==='status'){message(data.text);return;}
     const item=pending.get(data.id);if(!item)return;
     clearTimeout(item.timer);pending.delete(data.id);
     if(data.error)item.reject(new Error(data.error));else item.resolve(JSON.parse(data.result));
   };
   worker.onerror=event=>terminate(`Python could not load: ${event.message}. Check that the site runtime was built, then try Start Python.`);
   controls();message('Starting Python. The first load includes local WebAssembly, pandas, and Matplotlib…');
   const versions=await request('init',{files:workspace()},120000);
   ready=true;
   message(`Ready · Python ${versions.python} · pandas ${versions.pandas} · NumPy ${versions.numpy} · Matplotlib ${versions.matplotlib}. This browser environment differs from the local dependency lock.`);
   controls();
 }
 function output(result,container){
   container.replaceChildren();delete container.dataset.stale;container.dataset.error=String(Boolean(result.error));
   const text=document.createElement('pre');text.textContent=[result.stdout,result.stderr,result.error].filter(Boolean).join('\n')||'(No output; the cell may still have changed Python state.)';container.append(text);
   for(const png of result.figures){const img=document.createElement('img');img.src=`data:image/png;base64,${png}`;img.alt='Scientific figure generated by this Python cell';container.append(img);}
   q('[data-variables]').textContent=result.variables.map(v=>`${v.name}: ${v.value}`).join('\n')||'No user variables.';
   return !result.error;
 }
 async function runCell(index){
   await start();const cell=root.querySelector(`[data-cell="${index}"]`);
   cell.querySelector('[data-cell-count]').textContent=`In [${++execution}]`;
   const result=await request('run',{code:cell.querySelector('[data-cell-code]').value});
   q('[data-execution-log]').textContent+=`In [${execution}] → cell ${index+1}${result.error?' · error':''}\n`;
   return output(result,cell.querySelector('[data-cell-output]'));
 }
 async function runAll(fresh=false){
   if(fresh)terminate('Fresh kernel requested. Reloading the current workspace files…');
   for(let i=0;i<sources().length;i++)if(!await runCell(i))return false;
   return true;
 }
 async function act(action){
   if(busy)return;busy=true;controls();
   try{await action();}catch(error){message(error.message);}finally{busy=false;controls();persist();}
 }
 function choose(id){
   persist();terminate('Exercise selected. Python state starts empty; your source edits are saved locally.');
   lesson=lessons.find(l=>l.id===id)||lessons[0];
   const work=saved[lesson.id];q('[data-lab-title]').textContent=lesson.title;q('[data-lab-goal]').textContent=lesson.goal;
   q('[data-lab-steps]').replaceChildren(...lesson.steps.map(text=>{const li=document.createElement('li');li.textContent=text;return li;}));
   q('[data-lab-hint]').textContent=lesson.hint;q('[data-lab-explanation]').textContent=lesson.explanation;
   q('[data-prediction]').value=work?.prediction||'';
   q('[data-helper]').value=work?.helper||lesson.helper||'def clean_trials(trials, min_rt_s=0.2, max_rt_s=2.0):\n    return trials.loc[trials.reaction_time.between(min_rt_s, max_rt_s)].copy()\n';
   q('[data-config]').value=work?.config||BASE_CONFIG;
   q('[data-execution-log]').textContent='';q('[data-mission-result]').textContent='Not checked yet.';delete q('[data-mission-result]').dataset.state;
   q('[data-cells]').replaceChildren(...lesson.cells.map((spec,i)=>{
     const cell=document.createElement('section');cell.className='live-cell';cell.dataset.cell=i;
     const bar=document.createElement('div');bar.className='cell-toolbar';
     const count=document.createElement('span');count.dataset.cellCount='';count.textContent='In [ ]';
     const label=document.createElement('label');label.htmlFor=`python-cell-${i}`;label.textContent=`${i+1}. ${spec.title}`;
     const button=document.createElement('button');button.type='button';button.dataset.runCell=i;button.textContent=`Run cell ${i+1}`;
     const editor=document.createElement('textarea');editor.id=`python-cell-${i}`;editor.dataset.cellCode='';editor.className='code-editor';editor.spellcheck=false;editor.rows=Math.min(14,Math.max(4,spec.code.split('\n').length));editor.value=work?.sources?.[i]??spec.code;
     const result=document.createElement('div');result.className='cell-output';result.dataset.cellOutput='';result.setAttribute('aria-live','polite');
     bar.append(count,label,button);cell.append(bar,editor,result);return cell;
   }));
   for(const b of root.querySelectorAll('[data-scenario]'))b.setAttribute('aria-pressed',String(b.dataset.scenario===lesson.id));
   controls();root.dispatchEvent(new CustomEvent('workshop:lesson',{detail:{id:lesson.id}}));
 }
 root.addEventListener('input',event=>{if(event.target.matches('[data-cell-code],[data-helper],[data-config]'))invalidate();else if(event.target.matches('[data-prediction]'))persist();});
 root.addEventListener('keydown',event=>{
   if(event.target.matches('[data-cell-code]')&&event.key==='Enter'&&event.shiftKey){event.preventDefault();act(()=>runCell(Number(event.target.closest('[data-cell]').dataset.cell)));}
   // Keep Tab as normal keyboard navigation; no editor focus trap.
 });
 root.addEventListener('click',event=>{
   const b=event.target.closest('button');if(!b)return;
   if(b.matches('[data-run-cell]'))act(()=>runCell(Number(b.dataset.runCell)));
   else if(b.matches('[data-start-python]'))act(start);
   else if(b.matches('[data-run-all]'))act(()=>runAll(b.dataset.runAll==='fresh'));
   else if(b.matches('[data-stop-python]')){terminate('Stopped. The kernel and its variables were cleared; source edits are preserved.');}
   else if(b.matches('[data-scenario]'))choose(b.dataset.scenario);
   else if(b.matches('[data-check-mission]'))act(async()=>{
     if(lesson.freshCheck&&!await runAll(true)){q('[data-mission-result]').dataset.state='error';q('[data-mission-result]').textContent='Fresh run stopped at an error. Fix the cell, then check again.';return;}
     await start();const result=await request('run',{code:lesson.check});
     q('[data-mission-result]').dataset.state=result.error?'error':'passed';
     q('[data-mission-result]').textContent=result.error?result.error:`Passed · ${result.stdout}\nExplain: ${lesson.explanation}`;
   });
   else if(b.matches('[data-save-file]'))act(async()=>{await start();const path=b.dataset.saveFile;await request('save',{path,content:workspace()[path]});message(`Saved ${path} to the virtual workspace. Rerun imports/config loading and dependent cells; existing names do not update automatically.`);});
   else if(b.matches('[data-solution]')){
     const solution=lesson.solution;
     solution.cells?.forEach((code,i)=>{root.querySelector(`[data-cell="${i}"] [data-cell-code]`).value=code;});
     if(solution.helper)q('[data-helper]').value=solution.helper;if(solution.config)q('[data-config]').value=solution.config;
     persist();delete q('[data-mission-result]').dataset.state;terminate('Worked solution loaded into the editors. Start a fresh run to test it.');q('[data-mission-result]').textContent='Solution is visible. Predict what it changes, then run and check.';
   } else if(b.matches('[data-reset-lesson]')){delete saved[lesson.id];lesson=null;choose(root.querySelector('[data-scenario][aria-pressed=true]').dataset.scenario);persist();}
   else if(b.matches('[data-download]')){
     const kind=b.dataset.download;
     const text=kind==='notebook'?JSON.stringify(notebookExport(lesson,sources()),null,2):kind==='helper'?q('[data-helper]').value:q('[data-config]').value;
     const url=URL.createObjectURL(new Blob([text],{type:kind==='notebook'?'application/x-ipynb+json':'text/plain'}));
     const a=document.createElement('a');a.href=url;a.download=kind==='notebook'?`workshop-${lesson.id}.ipynb`:kind==='helper'?'helpers.py':'analysis.toml';a.click();setTimeout(()=>URL.revokeObjectURL(url),1000);
   }
 });
 const initial=location.hash.slice(1);choose(lessons.some(l=>l.id===initial)?initial:'state');
 window.addEventListener('beforeunload',()=>{persist();worker?.terminate();});
}
